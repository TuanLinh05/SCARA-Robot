function scara_export(out, ref, p, folder)
%SCARA_EXPORT Export simulation results to human-readable CSV (mm/deg) and MAT (SI).
%
% [EN] Writes two files into `output/data/` (or a custom `folder`):
%      1. `simulation.csv`: columns converted to degrees and millimeters for
%         easy inspection in Excel or plotting tools.
%      2. `simulation.mat`: full MATLAB structs `out`, `ref`, and `p` in SI units.
%
% [VI] Xuat ket qua mo phong ra 2 file trong thu muc `output/data/` (hoac `folder`):
%      1. `simulation.csv`: cac cot duoc doi sang do (deg) va milimet (mm) de
%         sinh vien de dang doc trong Excel hoac ve do thi.
%      2. `simulation.mat`: luu nguyen ven cac struct `out`, `ref`, `p` theo don vi SI.

    % -------------------------------------------------------------------------
    % Step 1: Set default output folder and create it if needed
    % Buoc 1: Chon thu muc xuat mac dinh va tao thu muc neu chua ton tai
    % -------------------------------------------------------------------------
    if nargin < 4
        folder = fullfile(p.outputRoot, 'data');
    end
    if ~isfolder(folder)
        mkdir(folder);
    end

    % -------------------------------------------------------------------------
    % Step 2: Build table with engineering units (deg, mm, steps) and write CSV/MAT
    % Buoc 2: Tao bang du lieu voi don vi ky thuat (do, mm, xung) va ghi file
    % -------------------------------------------------------------------------
    T = table( ...
        out.t, ...
        rad2deg(out.q(:, 1)), ...
        rad2deg(out.q(:, 2)), ...
        out.q(:, 3) * 1000, ...
        out.xyz(:, 1) * 1000, ...
        out.xyz(:, 2) * 1000, ...
        out.xyError * 1000, ...
        out.steps(:, 1), ...
        out.steps(:, 2), ...
        out.steps(:, 3), ...
        out.pen, ...
        out.allowed, ...
        'VariableNames', { ...
            't_s', 'q1_deg', 'q2_deg', 'z_mm', ...
            'x_mm', 'y_mm', 'model_error_mm', ...
            'Z_steps', 'A_steps', 'B_steps', 'pen', 'motion_allowed' ...
        });

    writetable(T, fullfile(folder, 'simulation.csv'));
    save(fullfile(folder, 'simulation.mat'), 'out', 'ref', 'p');
end